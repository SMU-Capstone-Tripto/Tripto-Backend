def find_area_codes(city: str, district: str = None) -> tuple[str | None, str | None]:
    """도시/지역명으로 (시도코드, 시군구코드) 반환. 관광공사 areaCode / sigunguCode."""
    sido_code = None
    sigungu_code = None

    if city:
        for key, code in SIDO_CODES.items():
            if key in city:
                sido_code = code
                break

    # 시도를 못 찾으면 city 자체가 시군구일 수 있음 (예: "강릉", "속초", "여수")
    if not sido_code and city:
        for suffix in ["", "시", "군", "구"]:
            candidate = city if city.endswith(("시", "군", "구")) else city + suffix
            for (s, g_name), g_code in SIGUNGU_CODES.items():
                if g_name == candidate:
                    sido_code = s
                    sigungu_code = g_code
                    break
            if sido_code:
                break

    if sido_code and district and not sigungu_code:
        for suffix in ["", "구", "시", "군"]:
            candidate = district if district.endswith(("시", "군", "구")) else district + suffix
            if (sido_code, candidate) in SIGUNGU_CODES:
                sigungu_code = SIGUNGU_CODES[(sido_code, candidate)]
                break

    return sido_code, sigungu_code


def fetch_area_list(sido_code: str, content_type_id: str, sigungu_code: str = None, num_rows: int = 20, arrange: str = "A") -> list:
    """지역 기반 콘텐츠 목록 조회 (areaBasedList2).
    arrange: A(제목순) | C(수정일순) | D(생성일순) | O/Q/R(대표이미지 있는 것 우선).
    ※ KorService2에는 조회수순(B)이 없다 — B를 넘기면 무시된다."""
    params = {
        "serviceKey": API_KEY,
        "numOfRows": str(num_rows),
        "pageNo": "1",
        "MobileOS": "ETC",
        "MobileApp": "Tripto",
        "_type": "json",
        "arrange": arrange,
        "areaCode": sido_code,
        "contentTypeId": content_type_id,
    }
    if sigungu_code:
        params["sigunguCode"] = sigungu_code

    resp = requests.get(LIST_URL, params=params, timeout=10)
    resp.raise_for_status()
    data = resp.json()

    try:
        items = data["response"]["body"]["items"]["item"]
        return items if isinstance(items, list) else [items]
    except (KeyError, TypeError):
        return []


_FEE_AMOUNT = re.compile(r'([1-9][0-9,]{2,})\s*원')


def parse_use_fee(text) -> int | None:
    """관광공사 usefee 문자열 → 성인 입장료(원).
      '무료' / '없음'            → 0
      '- 성인 19,000원 ...'      → 19000  (첫 번째 금액)
      '프로그램별 상이함' 등 불명   → None
    """
    if not text:
        return None
    s = str(text)
    m = _FEE_AMOUNT.search(s)
    if m:
        return int(m.group(1).replace(",", ""))
    if re.search(r"무료|없음", s):
        return 0
    return None


def fetch_use_fee(content_id: str, content_type_id: str) -> int | None:
    """detailIntro2로 해당 콘텐츠의 usefee 조회 후 파싱. 실패 시 None.
    contentTypeId 12(관광지)는 usefee 필드가 비어있고, 14(문화시설)에 실값이 들어있다."""
    params = {
        "serviceKey": API_KEY,
        "MobileOS": "ETC",
        "MobileApp": "Tripto",
        "_type": "json",
        "contentId": content_id,
        "contentTypeId": content_type_id,
    }
    try:
        resp = requests.get(INTRO_URL, params=params, timeout=10)
        resp.raise_for_status()
        items = resp.json()["response"]["body"].get("items")
        if not items:
            return None
        item = items["item"]
        item = item[0] if isinstance(item, list) else item
        return parse_use_fee(item.get("usefee", ""))
    except Exception:
        return None


