def find_area_codes(city: str, district: str = None) -> tuple[str | None, str | None]:
    """도시/지역명으로 (시도코드, 시군구코드) 반환"""
    sido_code = None
    sigungu_code = None

    if city:
        for key, code in SIDO_CODES.items():
            if key in city:
                sido_code = code
                break

    # 시도를 못 찾으면 city 자체가 시군구일 수 있음 (예: "강릉", "속초")
    if not sido_code and city:
        for suffix in ["", "시", "군", "구"]:
            candidate = city if city.endswith(("시", "군", "구")) else city + suffix
            for (s, g_name), g_code in SIGUNGU_CODES.items():
                if g_name == candidate:
                    sido_code = s
                    sigungu_code = g_code
                    break
            if sido_code:
                break

    if sido_code and district and not sigungu_code:
        for suffix in ["", "구", "시", "군"]:
            candidate = district if district.endswith(("시", "군", "구")) else district + suffix
            if (sido_code, candidate) in SIGUNGU_CODES:
                sigungu_code = SIGUNGU_CODES[(sido_code, candidate)]
                break

    return sido_code, sigungu_code


def fetch_area_list(sido_code: str, content_type_id: str, sigungu_code: str = None, num_rows: int = 20, arrange: str = "A") -> list:
    """지역 기반 콘텐츠 목록 조회 (areaBasedList2). arrange: A(제목순) | B(조회수순) | C(수정일순) | D(생성일순)"""
    params = {
        "serviceKey": API_KEY,
        "numOfRows": str(num_rows),
        "pageNo": "1",
        "MobileOS": "ETC",
        "MobileApp": "Tripto",
        "_type": "json",
        "arrange": arrange,
        "lDongRegnCd": sido_code,
        "contentTypeId": content_type_id,
    }
    if sigungu_code:
        params["lDongSignguCd"] = sigungu_code

    resp = requests.get(LIST_URL, params=params, timeout=10)
    resp.raise_for_status()
    data = resp.json()

    try:
        return data["response"]["body"]["items"]["item"]
    except (KeyError, TypeError):
        return []


def fetch_detail_info(content_id: str, content_type_id: str) -> list:
    """반복 정보 상세 조회 (detailInfo2) - 객실 정보 등"""
    params = {
        "serviceKey": API_KEY,
        "numOfRows": "50",
        "pageNo": "1",
        "MobileOS": "ETC",
        "MobileApp": "Tripto",
        "_type": "json",
        "contentId": content_id,
        "contentTypeId": content_type_id,
    }

    resp = requests.get(DETAIL_URL, params=params, timeout=10)
    resp.raise_for_status()
    data = resp.json()

    try:
        items = data["response"]["body"]["items"]
        return items["item"] if items else []
    except (KeyError, TypeError):
        return []
